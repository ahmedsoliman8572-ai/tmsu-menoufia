class I18n {
  constructor() {
    this.currentLang = localStorage.getItem('tmsu-lang') || 'ar';
    this.init();
  }

  init() {
    document.documentElement.setAttribute('data-lang', this.currentLang);
    document.documentElement.setAttribute('dir', this.currentLang === 'ar' ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', this.currentLang);
    this.translatePage();
  }

  toggle() {
    this.currentLang = this.currentLang === 'ar' ? 'en' : 'ar';
    localStorage.setItem('tmsu-lang', this.currentLang);

    // Add transition class for smooth switch
    document.body.classList.add('lang-transitioning');

    document.documentElement.setAttribute('data-lang', this.currentLang);
    document.documentElement.setAttribute('dir', this.currentLang === 'ar' ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', this.currentLang);

    this.translatePage();

    // Update font family
    if (this.currentLang === 'en') {
      document.body.style.fontFamily = "var(--ff-english)";
    } else {
      document.body.style.fontFamily = "var(--ff-body)";
    }

    setTimeout(() => {
      document.body.classList.remove('lang-transitioning');
    }, 500);
  }

  translatePage() {
    // Translate text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[key]) {
        el.textContent = translations[key][this.currentLang];
      }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (translations[key]) {
        el.placeholder = translations[key][this.currentLang];
      }
    });

    // Translate aria-labels
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      if (translations[key]) {
        el.setAttribute('aria-label', translations[key][this.currentLang]);
      }
    });

    // Update lang toggle button text
    const langBtns = document.querySelectorAll('.lang-toggle');
    langBtns.forEach(btn => {
      btn.textContent = translations['lang.switch'][this.currentLang];
    });

    // Update page title
    const pageTitleEl = document.querySelector('[data-i18n-title]');
    if (pageTitleEl) {
      const key = pageTitleEl.getAttribute('data-i18n-title');
      if (translations[key]) {
        document.title = translations[key][this.currentLang] + ' | ' +
          translations['hero.title'][this.currentLang] + ' - ' +
          translations['hero.subtitle'][this.currentLang];
      }
    }
  }

  t(key) {
    return translations[key] ? translations[key][this.currentLang] : key;
  }

  get lang() {
    return this.currentLang;
  }
}

// Global instance
const i18n = new I18n();
